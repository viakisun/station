/* ============================================================
   InterfaceSpec(ICD) 생성 — IF-P 는 wire 바인딩에서 파생(carries 동기), IF-L/IF-X 는
   본 스크립트의 하드테이블(provider/consumer 데이터 계약). 산출:
     profiles/interfaces/interface.*.json (검증) + src/generated/interfaces.ts (레지스트리)
   재생성: pnpm --filter @station/contracts interfaces
   ============================================================ */
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WIRE = join(ROOT, "profiles", "wire");
const OUTDIR = join(ROOT, "profiles", "interfaces");
const REG = join(ROOT, "src", "generated", "interfaces.ts");
mkdirSync(OUTDIR, { recursive: true });

const KIND = { "IF-P-MCU": "MCU", "IF-P-VPU": "VPU", "IF-P-LPU": "LPU", "IF-P-ACU": "ACU", "IF-P-TEL": "Telemetry" };
// 노드별 금지(NOT-carried, glob 접두) + heartbeat. ADR 산문의 역할 분리를 코드로.
// notCarried = 채널 네임스페이스 접두(glob). 노드가 *올려선 안 되는* 신호/이벤트.
const POLICY = {
  MCU: { notCarried: ["machine.autonomy.*", "machine.vision.*", "machine.localization.*", "machine.navigation.*", "crop.*"], hb: "machine.heartbeat.mcu" },
  VPU: { notCarried: ["machine.motion.*", "machine.autonomy.*", "machine.navigation.*", "machine.localization.*"], hb: "machine.heartbeat.vpu" },
  LPU: { notCarried: ["machine.motion.*", "machine.vision.*", "machine.autonomy.*"], hb: "machine.heartbeat.lpu" },
  ACU: { notCarried: ["machine.motion.*", "machine.vision.*", "machine.localization.*"], hb: "machine.heartbeat.acu" },
  Telemetry: { notCarried: ["machine.motion.*", "machine.autonomy.*", "machine.vision.*", "machine.localization.*"], hb: "machine.heartbeat.tel" },
};

const specs = [];

// 1) IF-P — wire 바인딩에서 파생.
for (const f of readdirSync(WIRE).filter((f) => f.endsWith(".json"))) {
  const b = JSON.parse(readFileSync(join(WIRE, f), "utf8"));
  const kind = KIND[b.interfaceId];
  if (!kind) continue;
  const pol = POLICY[kind];
  const hbCh = pol.hb;
  specs.push({
    id: b.interfaceId,
    class: "IF-P",
    provider: kind,
    consumer: "Agent",
    transport: b.transport,
    bindingRef: b.interfaceId,
    carries: {
      signals: [...(b.signals ?? []).map((e) => e.channel), hbCh],
      commands: (b.commands ?? []).map((e) => e.verb),
      events: (b.events ?? []).map((e) => e.code),
    },
    notCarried: pol.notCarried,
    heartbeat: { channel: hbCh, periodMs: 1000, timeoutMs: 3000 },
  });
}

// 2) IF-P-HMI + IF-L + IF-X — 하드테이블(데이터 계약).
specs.push(
  { id: "IF-P-HMI", class: "IF-P", provider: "HMI", consumer: "Agent", transport: "WS",
    carries: { commands: ["scan.start", "scan.stop"] }, notCarried: ["motion.set_speed_limit"],
    note: "현장 operator 명령. 최종 안전권한 아님(soft only)." },
  { id: "IF-L-HMI-AGG", class: "IF-L", provider: "Agent", consumer: "HMI", transport: "WS",
    note: "Agent 집계면 → HMI/콘솔(snapshot+signal/event/observation/ack). hmi-protocol.ts 가 기계가독 정의." },
  { id: "IF-L-ACU-LPU", class: "IF-L", provider: "LPU", consumer: "ACU",
    carries: { signals: ["machine.localization.pose"] }, note: "ACU 미션이 LPU pose 소비(Agent 경유)." },
  { id: "IF-L-ACU-VPU", class: "IF-L", provider: "VPU", consumer: "ACU",
    carries: { signals: ["machine.vision.worker_detected"] }, note: "ACU 가 VPU 인식 소비." },
  { id: "IF-L-POLICY-MCU", class: "IF-L", provider: "Agent", consumer: "MCU",
    carries: { commands: ["motion.set_speed_limit", "motion.stop"] }, note: "PolicyEngine 출력 → MCU 속도/정지." },
  { id: "IF-L-AGENT-OBS", class: "IF-L", provider: "Agent", consumer: "HMI",
    note: "App aggregator 합성 관측(OBS-*) 면." },
  { id: "IF-X-CLOUD-CMD", class: "IF-X", provider: "Cloud", consumer: "Agent", transport: "MQTT",
    note: "클라우드 요청 — Policy Engine 경유(권한 ④<③)." },
  { id: "IF-X-OTA", class: "IF-X", provider: "Cloud", consumer: "Agent", transport: "REST",
    note: "펌웨어/앱 OTA 다운로드." },
  { id: "IF-X-REGISTRY", class: "IF-X", provider: "Cloud", consumer: "Agent", transport: "REST",
    note: "노드/모듈/앱 레지스트리 동기." },
  { id: "IF-X-TEL-UP", class: "IF-X", provider: "Agent", consumer: "Cloud", transport: "MQTT",
    note: "텔레메트리 업링크(흡수 신호 → 클라우드)." },
);

// 쓰기 — 인스턴스 JSON.
for (const s of specs) writeFileSync(join(OUTDIR, `interface.${s.id}.json`), JSON.stringify(s, null, 2) + "\n");

// 레지스트리 TS.
const banner = "/* AUTO-GENERATED by scripts/gen-interface-specs.mjs — DO NOT EDIT.\n   재생성: pnpm --filter @station/contracts interfaces */";
const body = `${banner}
import type { InterfaceSpec } from "./interface-spec";

export const INTERFACES: Record<string, InterfaceSpec> = {
${specs.map((s) => `  ${JSON.stringify(s.id)}: ${JSON.stringify(s)},`).join("\n")}
};

export const ALL_INTERFACES: readonly InterfaceSpec[] = Object.values(INTERFACES);
/** 노드 kind 의 IF-P 스펙(provider=kind, class=IF-P). */
export const ifpFor = (provider: string): InterfaceSpec | undefined =>
  ALL_INTERFACES.find((i) => i.class === "IF-P" && i.provider === provider);
export const consumersOf = (provider: string): InterfaceSpec[] =>
  ALL_INTERFACES.filter((i) => i.provider === provider);
`;
writeFileSync(REG, body);
console.log(`✓ ${specs.length} InterfaceSpec → profiles/interfaces/ + src/generated/interfaces.ts`);
