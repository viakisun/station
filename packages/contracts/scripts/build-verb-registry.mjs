/* ============================================================
   STATION Contracts — command verb 레지스트리 빌더.
   examples/node.*.json(commands[]) + examples/app.*.json(provides.commands[]) 를
   집계해 canonical verb 레지스트리 src/generated/verbs.ts 생성.
   verb 가 둘 이상의 provider 에 중복 선언되면 exit 1(충돌).
   재생성: pnpm --filter @station/contracts verbs
   ============================================================ */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const EX = join(ROOT, "examples");
const OUT = join(ROOT, "src", "generated", "verbs.ts");

// namespace.ts SAFETY_VERBS 와 동기(안전 verb = guarded). 변경 시 양쪽 같이.
const SAFETY = new Set([
  "ee.pinch", "ee.release", "ee.calibrate", "arm.move", "arm.calibrate",
  "vision.calibrate", "motion.stop", "autonomy.pause", "autonomy.slow_down",
]);

/** verb → { source, provider(node kind | appId), ownerOrg } */
const reg = {};
const conflicts = [];
const add = (verb, entry) => {
  if (reg[verb] && reg[verb].provider !== entry.provider) {
    conflicts.push(`${verb}: ${reg[verb].provider} vs ${entry.provider}`);
    return;
  }
  reg[verb] = entry;
};

for (const f of readdirSync(EX).filter((f) => f.endsWith(".json"))) {
  const d = JSON.parse(readFileSync(join(EX, f), "utf8"));
  if (f.startsWith("node.")) {
    for (const v of d.commands ?? []) add(v, { source: "node", provider: d.kind, ownerOrg: d.ownerOrg });
  } else if (f.startsWith("app.")) {
    for (const v of d.provides?.commands ?? []) add(v, { source: "app", provider: d.appId, ownerOrg: d.ownerOrg });
  }
}

if (conflicts.length) {
  console.error("✗ verb 충돌:\n  " + conflicts.join("\n  "));
  process.exit(1);
}

const verbs = Object.keys(reg).sort();
const entries = verbs
  .map((v) => `  ${JSON.stringify(v)}: { verb: ${JSON.stringify(v)}, source: ${JSON.stringify(reg[v].source)}, provider: ${JSON.stringify(reg[v].provider)}, ownerOrg: ${JSON.stringify(reg[v].ownerOrg)}, safety: ${SAFETY.has(v)} },`)
  .join("\n");

const banner = "/* AUTO-GENERATED by scripts/build-verb-registry.mjs — DO NOT EDIT.\n   재생성: pnpm --filter @station/contracts verbs */";
const out = `${banner}

export interface VerbEntry {
  verb: string;
  source: "node" | "app";
  provider: string; // node kind(MCU…) 또는 appId(station.app.*)
  ownerOrg: string;
  safety: boolean; // 안전 verb(가드 대상)
}

/** canonical command verb 레지스트리 — examples/{node,app}.*.json 에서 집계(무충돌 보장). */
export const COMMAND_VERBS: Record<string, VerbEntry> = {
${entries}
};

export const ALL_VERBS: readonly string[] = Object.keys(COMMAND_VERBS);
export const isKnownVerb = (v: string): boolean => v in COMMAND_VERBS;
`;

writeFileSync(OUT, out);
console.log(`✓ ${verbs.length} verbs → src/generated/verbs.ts`);
